assert.equal(loaderBlock.length, 0x1904d - 0x18ef0, 'captured loader TB byte range must be exact');

function instrumentInvoke(source: string): string {
  const pattern = /function invoke_iijjii\(index,a1,a2,a3,a4,a5\)\{/g;
  const matches = source.match(pattern) ?? [];
  assert.equal(matches.length, 1, 'vendored Unicorn runtime must expose exactly one invoke_iijjii wrapper');
  return source.replace(pattern, (match) => `${match}globalThis.${INVOKE_KEY}=[index,a1,a2,a3,a4,a5];`);
}

function diagnostic(): string {
  const values = (globalThis as DiagnosticGlobal)[INVOKE_KEY];
  if (!Array.isArray(values)) return '<unobserved>';
  return values.map((value, index) => {
    if (typeof value === 'bigint') return `a${index}=0x${BigInt.asUintN(64, value).toString(16)}`;
    if (typeof value === 'number' && Number.isFinite(value)) return `a${index}=${value}/0x${(value >>> 0).toString(16)}`;
    return `a${index}=${String(value)}`;
  }).join(',');
}

function probePrefix(module: UnicornModule, endImageAddress: number): { supported: boolean; detail: string } {
  const engine = new module.Unicorn(module.ARCH_X86, module.MODE_64);
  const length = endImageAddress - 0x18ef0;
  assert.ok(length > 0 && length <= loaderBlock.length);
  const bytes = [...loaderBlock.subarray(0, length), 0xc3]; // RET terminates translation at the chosen instruction boundary.
  const codePage = Math.floor(START / PAGE) * PAGE;
  const stackPage = Math.floor(STACK_TOP / PAGE) * PAGE;
  delete (globalThis as DiagnosticGlobal)[INVOKE_KEY];
  try {
    engine.mem_map(codePage, PAGE, module.PROT_ALL);
    engine.mem_write(START, bytes);
    engine.mem_map(stackPage, PAGE, module.PROT_READ | module.PROT_WRITE);
    engine.reg_write_i64(module.X86_REG_RSP, BigInt(STACK_TOP));
    engine.reg_write_i64(module.X86_REG_RBP, BigInt(STACK_TOP));
    // count=1 stops after the first PUSH. Translation still has to decode and
    // lower the entire synthetic TB through the inserted RET.
    engine.emu_start(START, START + bytes.length, 0, 1);
    assert.equal(engine.reg_read_i64(module.X86_REG_RSP), BigInt(STACK_TOP - 8));
    return { supported: true, detail: diagnostic() };
  } catch (cause) {
    let detail = cause instanceof Error ? cause.message : String(cause);
    try { detail += ` (errno ${engine.errno()}: ${module.strerror(engine.errno())})`; } catch { /* original error is authoritative */ }
    detail += ` invoke=${diagnostic()}`;
    return { supported: false, detail };
  } finally {
    engine.close();
  }
}

const checkpoints = [
  0x18f89, // loads + integer ALU, before the first RIP-relative store
  0x18fbd, // adds RIP-relative stores and more global loads
  0x18fed, // adds stack-local stores and global feature-word updates
  0x19025, // extends through additional RIP-relative read/modify/write sequences
  0x1904d  // complete initial straight-line region, immediately before first Jcc
] as const;

const temp = mkdtempSync(join(tmpdir(), 'asm-graph-unicorn-high-rip-tb-'));
try {
  const runtime = join(temp, 'unicorn_x86.cjs');
  const source = readFileSync(resolve('public/vendor/unicorn/unicorn_x86.js'), 'utf8');
  writeFileSync(runtime, instrumentInvoke(source));
  const factory = createRequire(import.meta.url)(runtime) as UnicornFactory;
  const module = await factory();

  for (const end of checkpoints) {
    const result = probePrefix(module, end);
    console.log(`Unicorn high-RIP TB prefix 0x18ef0..0x${end.toString(16)}: ${result.supported ? 'PASS' : 'FAIL'} · ${result.detail}`);
    assert.equal(result.supported, true, `high-RIP loader translation prefix ending at 0x${end.toString(16)} failed: ${result.detail}`);
  }

  console.log('Unicorn high-RIP translation-block smoke: PASS');
} finally {
  delete (globalThis as DiagnosticGlobal)[INVOKE_KEY];
  rmSync(temp, { recursive: true, force: true });
}
